/**
 * Points the frontend at a deployed stack and, unless --env-only is passed,
 * builds it and publishes the bundle to the CloudFront site.
 *
 * Reads infra/cdk-outputs.json, which `cdk deploy --outputs-file cdk-outputs.json`
 * writes. Publishing shells out to the AWS CLI with the caller's credentials.
 *
 *   node tools/publish-frontend.mjs --env-only   # frontend/.env for `vite dev`
 *   node tools/publish-frontend.mjs              # .env + build + upload + invalidate
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputsPath = path.join(root, 'infra', 'cdk-outputs.json');
const envPath = path.join(root, 'frontend', '.env');
const envOnly = process.argv.includes('--env-only');

function fail(message) {
  console.error(message);
  process.exit(1);
}

if (!existsSync(outputsPath)) {
  fail(
    `Missing ${path.relative(root, outputsPath)}. Deploy first:\n` +
      '  npx -w infra cdk deploy --all --outputs-file cdk-outputs.json',
  );
}
const outputs = JSON.parse(readFileSync(outputsPath, 'utf8'));

function output(stack, key) {
  const value = outputs[stack]?.[key];
  if (typeof value !== 'string' || value === '') {
    fail(`Missing output ${stack}.${key} in ${path.relative(root, outputsPath)}`);
  }
  return value;
}

// The mock configuration trusts a localhost JWKS. Refuse to build on top of it rather
// than risk that variable reaching a deployed bundle.
if (
  existsSync(envPath) &&
  readFileSync(envPath, 'utf8').includes('VITE_MOCK_JWKS_URI')
) {
  fail(
    'frontend/.env is the local mock configuration. Move it to frontend/.env.mock ' +
      '(used by `npm run dev:mock`) and re-run.',
  );
}

const region = output('KbAuthStack', 'Region');
const env = {
  VITE_USER_POOL_ID: output('KbAuthStack', 'UserPoolId'),
  VITE_USER_POOL_CLIENT_ID: output('KbAuthStack', 'UserPoolClientId'),
  VITE_COGNITO_DOMAIN: `https://${output('KbAuthStack', 'CognitoDomainPrefix')}.auth.${region}.amazoncognito.com`,
  VITE_API_URL: output('KbApiStack', 'HttpApiUrl'),
  VITE_CHAT_URL: output('KbApiStack', 'ChatFunctionUrl'),
  VITE_AWS_REGION: region,
};
writeFileSync(
  envPath,
  '# Generated by tools/publish-frontend.mjs from infra/cdk-outputs.json.\n' +
    Object.entries(env)
      .map(([key, value]) => `${key}=${value}\n`)
      .join(''),
);
console.log(`Wrote ${path.relative(root, envPath)}`);

if (envOnly) {
  process.exit(0);
}

// AWS CLI v2 pipes command output into a pager on a terminal, which would leave the
// invalidation step waiting for a keypress after the work is already done.
const run = (command, args) =>
  execFileSync(command, args, {
    cwd: root,
    stdio: 'inherit',
    env: { ...process.env, AWS_PAGER: '' },
  });

run('npm', ['run', '-w', 'frontend', 'build']);
run('aws', [
  's3',
  'sync',
  path.join('frontend', 'dist'),
  `s3://${output('KbFrontendStack', 'SiteBucketName')}`,
  '--delete',
  '--region',
  region,
]);
run('aws', [
  'cloudfront',
  'create-invalidation',
  '--distribution-id',
  output('KbFrontendStack', 'DistributionId'),
  '--paths',
  '/*',
]);
console.log(`\nPublished: ${output('KbFrontendStack', 'FrontendUrl')}`);
