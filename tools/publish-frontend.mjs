/**
 * Points the frontend at a deployed stack and, unless --env-only is passed,
 * builds it and publishes the bundle to the CloudFront site.
 *
 * Reads infra/cdk-outputs.json, which `cdk deploy --outputs-file cdk-outputs.json`
 * writes, or with --from-stacks asks CloudFormation for the same outputs (what CI
 * does, since that file is never committed). Publishing shells out to the AWS CLI
 * with the caller's credentials.
 *
 *   node tools/publish-frontend.mjs --env-only     # frontend/.env for `vite dev`
 *   node tools/publish-frontend.mjs                # .env + build + upload + invalidate
 *   node tools/publish-frontend.mjs --from-stacks  # same, outputs read from AWS
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputsPath = path.join(root, 'infra', 'cdk-outputs.json');
const envPath = path.join(root, 'frontend', '.env');
const envOnly = process.argv.includes('--env-only');
const fromStacks = process.argv.includes('--from-stacks');
const OUTPUT_STACKS = ['KbAuthStack', 'KbApiStack', 'KbFrontendStack'];

function fail(message) {
  console.error(message);
  process.exit(1);
}

// AWS CLI v2 pipes command output into a pager on a terminal, which would leave a
// command waiting for a keypress after its work is already done.
const awsEnv = { ...process.env, AWS_PAGER: '' };

function stackOutputs(stack) {
  const raw = execFileSync(
    'aws',
    [
      'cloudformation',
      'describe-stacks',
      '--stack-name',
      stack,
      '--query',
      'Stacks[0].Outputs',
      '--output',
      'json',
    ],
    { cwd: root, encoding: 'utf8', env: awsEnv },
  );
  return Object.fromEntries(
    (JSON.parse(raw) ?? []).map((entry) => [entry.OutputKey, entry.OutputValue]),
  );
}

if (!fromStacks && !existsSync(outputsPath)) {
  fail(
    `Missing ${path.relative(root, outputsPath)}. Deploy first:\n` +
      '  npx -w infra cdk deploy --all --outputs-file cdk-outputs.json\n' +
      'or pass --from-stacks to read the outputs from CloudFormation.',
  );
}
const outputsSource = fromStacks
  ? 'CloudFormation'
  : path.relative(root, outputsPath);
const outputs = fromStacks
  ? Object.fromEntries(OUTPUT_STACKS.map((stack) => [stack, stackOutputs(stack)]))
  : JSON.parse(readFileSync(outputsPath, 'utf8'));

function output(stack, key) {
  const value = outputs[stack]?.[key];
  if (typeof value !== 'string' || value === '') {
    fail(`Missing output ${stack}.${key} in ${outputsSource}`);
  }
  return value;
}

// The mock configuration trusts a localhost issuer. Refuse to build on top of it rather
// than risk that issuer reaching a deployed bundle.
if (
  existsSync(envPath) &&
  /^VITE_OIDC_ISSUER=http:\/\/localhost/m.test(readFileSync(envPath, 'utf8'))
) {
  fail(
    'frontend/.env points at a localhost issuer. Move it to frontend/.env.mock ' +
      '(used by `npm run dev:mock`) and re-run.',
  );
}

const region = output('KbAuthStack', 'Region');
const issuer = `https://cognito-idp.${region}.amazonaws.com/${output('KbAuthStack', 'UserPoolId')}`;
const hostedUi = `https://${output('KbAuthStack', 'CognitoDomainPrefix')}.auth.${region}.amazoncognito.com`;
const env = {
  VITE_OIDC_ISSUER: issuer,
  VITE_OIDC_CLIENT_ID: output('KbAuthStack', 'UserPoolClientId'),
  VITE_OIDC_AUTHORIZE_URL: `${hostedUi}/oauth2/authorize`,
  VITE_OIDC_TOKEN_URL: `${hostedUi}/oauth2/token`,
  VITE_OIDC_JWKS_URL: `${issuer}/.well-known/jwks.json`,
  VITE_OIDC_SCOPE: 'openid email profile kb-api/access',
  VITE_OIDC_LOGOUT_URL: `${hostedUi}/logout`,
  VITE_OIDC_LOGOUT_MODE: 'cognito',
  VITE_API_URL: output('KbApiStack', 'HttpApiUrl'),
  // The chat function answers at its URL root, which deployed clients already use.
  VITE_CHAT_URL: output('KbApiStack', 'ChatFunctionUrl'),
};
writeFileSync(
  envPath,
  `# Generated by tools/publish-frontend.mjs from ${outputsSource}.\n` +
    Object.entries(env)
      .map(([key, value]) => `${key}=${value}\n`)
      .join(''),
);
console.log(`Wrote ${path.relative(root, envPath)}`);

if (envOnly) {
  process.exit(0);
}

const run = (command, args) =>
  execFileSync(command, args, { cwd: root, stdio: 'inherit', env: awsEnv });

run('npm', ['run', '-w', 'frontend', 'build']);
run('aws', [
  's3',
  'sync',
  path.join('frontend', 'dist'),
  `s3://${output('KbFrontendStack', 'SiteBucketName')}`,
  '--delete',
  '--region',
  region,
]);
run('aws', [
  'cloudfront',
  'create-invalidation',
  '--distribution-id',
  output('KbFrontendStack', 'DistributionId'),
  '--paths',
  '/*',
]);
console.log(`\nPublished: ${output('KbFrontendStack', 'FrontendUrl')}`);
